export const formatPrice = (amount) =>
  new Intl.NumberFormat("en-PH", {
    style: "currency",
    currency: "PHP",
    maximumFractionDigits: 0,
  }).format(amount);

export const priceForOption = (item, option) => {
  const match = String(option || "").match(/\+₱\s?([\d,]+)/);
  const extra = match ? Number(match[1].replace(/,/g, "")) : 0;
  return item.price + extra;
};
