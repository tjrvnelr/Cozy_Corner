-- Customers table
CREATE TABLE IF NOT EXISTS customers (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(120) NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT customers_name_length_chk
    CHECK (CHAR_LENGTH(TRIM(name)) BETWEEN 2 AND 120)
);

-- Menu items table (New table to store the food menu)
CREATE TABLE IF NOT EXISTS menu_items (
  id TEXT PRIMARY KEY,
  name VARCHAR(160) NOT NULL,
  category VARCHAR(50) NOT NULL,
  description TEXT,
  price DECIMAL(10, 2) NOT NULL,
  image TEXT,
  ingredients TEXT[], -- PostgreSQL array for ingredients
  popular BOOLEAN DEFAULT false,
  available BOOLEAN DEFAULT true,
  options TEXT[], -- PostgreSQL array for options
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Orders table
CREATE TABLE IF NOT EXISTS orders (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_number VARCHAR(32) NOT NULL UNIQUE,
  customer_id BIGINT NOT NULL REFERENCES customers(id),
  fulfillment_method VARCHAR(16) NOT NULL,
  subtotal DECIMAL(10, 2) NOT NULL,
  delivery_fee DECIMAL(10, 2) NOT NULL DEFAULT 0,
  total DECIMAL(10, 2) NOT NULL,
  ordered_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT orders_fulfillment_method_chk
    CHECK (fulfillment_method IN ('pickup', 'delivery')),
  CONSTRAINT orders_subtotal_chk CHECK (subtotal >= 0),
  CONSTRAINT orders_delivery_fee_chk CHECK (delivery_fee >= 0),
  CONSTRAINT orders_total_chk CHECK (total >= 0)
);

CREATE INDEX orders_customer_id_idx ON orders (customer_id);
CREATE INDEX orders_ordered_at_idx ON orders (ordered_at);

-- Order Items table
CREATE TABLE IF NOT EXISTS order_items (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id BIGINT NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
  menu_item_id TEXT NOT NULL REFERENCES menu_items(id),
  item_name VARCHAR(160) NOT NULL,
  option_name VARCHAR(120),
  quantity INT NOT NULL,
  unit_price DECIMAL(10, 2) NOT NULL,
  line_total DECIMAL(10, 2) NOT NULL,
  CONSTRAINT order_items_quantity_chk CHECK (quantity > 0),
  CONSTRAINT order_items_unit_price_chk CHECK (unit_price >= 0),
  CONSTRAINT order_items_line_total_chk CHECK (line_total >= 0)
);

CREATE INDEX order_items_order_id_idx ON order_items (order_id);

-- Payments table
CREATE TABLE IF NOT EXISTS payments (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id BIGINT NOT NULL UNIQUE REFERENCES orders(id) ON DELETE CASCADE,
  method VARCHAR(16) NOT NULL,
  status VARCHAR(24) NOT NULL,
  paid_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT payments_method_chk
    CHECK (method IN ('gcash', 'maya', 'cashier')),
  CONSTRAINT payments_status_chk
    CHECK (status IN ('paid', 'pay_at_cashier', 'failed', 'refunded'))
);

-- Customer Order Summary View
CREATE OR REPLACE VIEW customer_order_summary AS
SELECT
  o.id AS order_id,
  o.order_number,
  c.name AS customer_name,
  o.fulfillment_method,
  o.total,
  p.method AS payment_method,
  p.status AS payment_status,
  o.ordered_at
FROM orders AS o
JOIN customers AS c ON c.id = o.customer_id
LEFT JOIN payments AS p ON p.order_id = o.id;

-- Public visitors may read the menu, but orders are written through the
-- transactional function below instead of granting direct table writes.
ALTER TABLE menu_items ENABLE ROW LEVEL SECURITY;
ALTER TABLE customers ENABLE ROW LEVEL SECURITY;
ALTER TABLE orders ENABLE ROW LEVEL SECURITY;
ALTER TABLE order_items ENABLE ROW LEVEL SECURITY;
ALTER TABLE payments ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Anyone can read available menu items" ON menu_items;
CREATE POLICY "Anyone can read available menu items"
  ON menu_items
  FOR SELECT
  TO anon, authenticated
  USING (true);

CREATE OR REPLACE FUNCTION public.create_order(
  p_customer_name TEXT,
  p_order_number TEXT,
  p_fulfillment_method TEXT,
  p_subtotal NUMERIC,
  p_delivery_fee NUMERIC,
  p_total NUMERIC,
  p_payment_method TEXT,
  p_payment_status TEXT,
  p_items JSONB
)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  v_customer_id BIGINT;
  v_order_id BIGINT;
  v_item JSONB;
BEGIN
  IF CHAR_LENGTH(TRIM(p_customer_name)) NOT BETWEEN 2 AND 120 THEN
    RAISE EXCEPTION 'Customer name must be between 2 and 120 characters';
  END IF;

  IF jsonb_typeof(p_items) <> 'array' OR jsonb_array_length(p_items) = 0 THEN
    RAISE EXCEPTION 'An order must contain at least one item';
  END IF;

  INSERT INTO customers (name)
  VALUES (TRIM(p_customer_name))
  RETURNING id INTO v_customer_id;

  INSERT INTO orders (
    order_number,
    customer_id,
    fulfillment_method,
    subtotal,
    delivery_fee,
    total
  )
  VALUES (
    p_order_number,
    v_customer_id,
    p_fulfillment_method,
    p_subtotal,
    p_delivery_fee,
    p_total
  )
  RETURNING id INTO v_order_id;

  FOR v_item IN SELECT value FROM jsonb_array_elements(p_items)
  LOOP
    INSERT INTO order_items (
      order_id,
      menu_item_id,
      item_name,
      option_name,
      quantity,
      unit_price,
      line_total
    )
    VALUES (
      v_order_id,
      v_item->>'id',
      v_item->>'name',
      NULLIF(v_item->>'option', ''),
      (v_item->>'quantity')::INT,
      (v_item->>'unitPrice')::NUMERIC,
      (v_item->>'lineTotal')::NUMERIC
    );
  END LOOP;

  INSERT INTO payments (order_id, method, status, paid_at)
  VALUES (
    v_order_id,
    p_payment_method,
    p_payment_status,
    CASE WHEN p_payment_status = 'paid' THEN CURRENT_TIMESTAMP ELSE NULL END
  );

  RETURN jsonb_build_object(
    'order_id', v_order_id,
    'order_number', p_order_number
  );
END;
$$;

REVOKE ALL ON FUNCTION public.create_order(TEXT, TEXT, TEXT, NUMERIC, NUMERIC, NUMERIC, TEXT, TEXT, JSONB) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.create_order(TEXT, TEXT, TEXT, NUMERIC, NUMERIC, NUMERIC, TEXT, TEXT, JSONB) TO anon, authenticated;
